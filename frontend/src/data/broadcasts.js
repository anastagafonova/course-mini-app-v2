/**
 * Преобразует ссылку на видео в embed-URL для iframe.
 * Поддерживает Kinescope, YouTube и VK.
 */
export function resolveEmbedUrl(videoUrl) {
  const raw = String(videoUrl || "").trim();
  if (!raw) return null;

  if (
    raw.includes("kinescope.io/embed/") ||
    raw.includes("youtube.com/embed/") ||
    raw.includes("youtube-nocookie.com/embed/") ||
    raw.includes("vk.com/video_ext.php")
  ) {
    return raw;
  }

  const kinescopeMatch = raw.match(/kinescope\.io\/(?:watch\/)?([a-zA-Z0-9_-]+)/);
  if (kinescopeMatch) {
    return `https://kinescope.io/embed/${kinescopeMatch[1]}`;
  }

  const youtubeWatchMatch = raw.match(
    /(?:youtube\.com\/watch\?v=|youtu\.be\/|youtube\.com\/shorts\/)([a-zA-Z0-9_-]{6,})/
  );
  if (youtubeWatchMatch) {
    return `https://www.youtube.com/embed/${youtubeWatchMatch[1]}`;
  }

  const vkMatch = raw.match(/vk\.com\/video(-?\d+)_(\d+)/);
  if (vkMatch) {
    return `https://vk.com/video_ext.php?oid=${vkMatch[1]}&id=${vkMatch[2]}&hd=2`;
  }

  return raw;
}
